#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_font_cursive_renders() {
        let lines = StrokeFont::render_text_styled("ПРИВЕТ WORLD", 14.0, FontStyle::Cursive);
        assert!(!lines.is_empty(), "Cursive font must generate polylines");
        for line in &lines {
            assert!(line.points.len() >= 2);
        }
    }
}
